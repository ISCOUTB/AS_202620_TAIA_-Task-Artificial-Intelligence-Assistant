"""El verificador de dependencias Dart debe detectar lock manipulado o incompleto."""

from __future__ import annotations

import importlib.util
import json
import urllib.error
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location(
    "verificar_dependencias_dart", ROOT / "tools/verificar_dependencias_dart.py"
)
verificador = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(verificador)

SHA_ASYNC = "e2eb0491ba5ddb6177742d2da23904574082139b07c1e33b8503b9f46f3e1a37"
SHA_CUPERTINO = "41e005c33bd814be4d3096aff55b1908d419fde52ca656c8c47719ec745873cd"

LOCK = """# Generated by pub
packages:
  async:
    dependency: transitive
    description:
      name: async
      sha256: {sha_async}
      url: "https://pub.dev"
    source: hosted
    version: "2.13.1"
  cupertino_icons:
    dependency: "direct main"
    description:
      name: cupertino_icons
      sha256: "{sha_cupertino}"
      url: "https://pub.dev"
    source: hosted
    version: "1.0.9"
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
  flutter_test:
    dependency: "direct dev"
    description: flutter
    source: sdk
    version: "0.0.0"
sdks:
  dart: ">=3.13.1 <4.0.0"
""".format(sha_async=SHA_ASYNC, sha_cupertino=SHA_CUPERTINO)

PUBSPEC = """name: taia
environment:
  sdk: ^3.13.1

dependencies:
  flutter:
    sdk: flutter
  cupertino_icons: ^1.0.8

dev_dependencies:
  flutter_test:
    sdk: flutter
"""


def test_lock_valido_pasa():
    resultado = verificador.analizar(LOCK, PUBSPEC)

    assert resultado["problemas"] == []
    assert resultado["veredicto"] == "ok"
    assert resultado["paquetes"] == 4
    assert resultado["por_origen"] == {"hosted": 2, "sdk": 2}
    assert resultado["directas_declaradas"] == {
        "main": ["cupertino_icons", "flutter"],
        "dev": ["flutter_test"],
    }


def test_paquete_sin_sha256():
    resultado = verificador.analizar(LOCK.replace("      sha256: {}".format(SHA_ASYNC), "      sha256:"), PUBSPEC)

    assert resultado["sin_sha256"] == ["async"]
    assert any("async: sin sha256 valido" in p for p in resultado["problemas"])


def test_origen_alojado_que_no_es_pub_dev():
    resultado = verificador.analizar(LOCK.replace('url: "https://pub.dev"', 'url: "https://ejemplo.test"'), PUBSPEC)

    assert any("async: el origen alojado no es https://pub.dev" in p for p in resultado["problemas"])


def test_dependencia_git_no_permitida():
    documento = LOCK.replace("    source: hosted\n    version: \"2.13.1\"", "    source: git\n    version: \"2.13.1\"")

    resultado = verificador.analizar(documento, PUBSPEC)

    assert resultado["origenes_no_permitidos"] == ["async (git)"]
    assert any("async: origen no permitido 'git'" in p for p in resultado["problemas"])


def test_paquete_sin_version():
    documento = LOCK.replace('    version: "2.13.1"\n', "")

    resultado = verificador.analizar(documento, PUBSPEC)

    assert resultado["sin_version"] == ["async"]
    assert any("async: sin version en el lock" in p for p in resultado["problemas"])


def test_tipo_de_dependencia_desconocido():
    documento = LOCK.replace("dependency: transitive", "dependency: prestada")

    resultado = verificador.analizar(documento, PUBSPEC)

    assert any("async: tipo de dependencia desconocido 'prestada'" in p for p in resultado["problemas"])


def test_directa_declarada_ausente_del_lock():
    pubspec = PUBSPEC.replace("  cupertino_icons: ^1.0.8\n", "  cupertino_icons: ^1.0.8\n  http: ^1.2.0\n")

    resultado = verificador.analizar(LOCK, pubspec)

    assert resultado["directas_faltantes"] == ["http"]
    assert any("http: dependencia directa declarada pero ausente del lock" in p for p in resultado["problemas"])


def test_directa_con_tipo_incorrecto():
    pubspec = PUBSPEC.replace("  cupertino_icons: ^1.0.8\n", "").replace(
        "dev_dependencies:\n", "dev_dependencies:\n  cupertino_icons: ^1.0.8\n"
    )

    resultado = verificador.analizar(LOCK, pubspec)

    assert any("cupertino_icons: el lock la marca como 'direct main'" in p for p in resultado["problemas"])


def test_directa_del_lock_que_no_esta_en_pubspec():
    documento = LOCK.replace(
        "  async:\n    dependency: transitive",
        "  async:\n    dependency: \"direct main\"",
    )

    resultado = verificador.analizar(documento, PUBSPEC)

    assert any("async: el lock la marca como directa pero pubspec.yaml no la declara" in p for p in resultado["problemas"])


def test_osv_reporta_vulnerabilidades():
    def transporte(cuerpo: bytes) -> dict:
        consultas = json.loads(cuerpo.decode("utf-8"))["queries"]
        return {
            "results": [
                {"vulns": [{"id": "GHSA-test", "summary": "fallo de prueba", "aliases": ["CVE-2026-1"]}]}
                if indice == 0
                else {}
                for indice in range(len(consultas))
            ]
        }

    resultado = verificador.analizar(LOCK, PUBSPEC, transporte=transporte, online=True)

    assert resultado["osv_consultado"] is True
    assert len(resultado["vulnerabilidades"]) == 1
    assert resultado["vulnerabilidades"][0]["id"] == "GHSA-test"
    assert any("GHSA-test fallo de prueba" in p for p in resultado["problemas"])


def test_osv_sin_red_no_revienta():
    def transporte(_cuerpo: bytes) -> dict:
        raise urllib.error.URLError("sin red")

    resultado = verificador.analizar(LOCK, PUBSPEC, transporte=transporte, online=True)

    assert any("no se pudo consultar OSV" in p for p in resultado["problemas"])


def test_lock_del_repositorio_es_consistente():
    resultado = verificador.analizar(
        verificador.LOCK.read_text(encoding="utf-8"),
        verificador.PUBSPEC.read_text(encoding="utf-8"),
    )

    assert resultado["problemas"] == []
    assert resultado["paquetes"] > 0
    assert resultado["por_origen"]["hosted"] > 0


def test_lock_sin_bloque_de_sdks():
    documento = LOCK.split("sdks:")[0]

    resultado = verificador.analizar(documento, PUBSPEC)

    assert any("no declara la version minima de Dart" in p for p in resultado["problemas"])


def test_pubspec_y_lock_discrepan_en_la_version_de_dart():
    pubspec = PUBSPEC.replace("sdk: ^3.13.1", "sdk: ^3.20.0")

    resultado = verificador.analizar(LOCK, pubspec)

    assert resultado["sdks"]["dart"] == ">=3.13.1 <4.0.0"
    assert any("pubspec.yaml exige Dart 3.20.0" in p for p in resultado["problemas"])
